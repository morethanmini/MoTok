// 제자리 홀드는 호 길이가 0이라 멈춘 점으로만 보여 무슨 노트인지 읽히지 않았다.
/** 홀드 중 존을 벗어나도 이 시간까지는 봐준다(트래킹 흔들림 관용) */
export const HOLD_GRACE_MS = 450
/** 홀드 tail을 이 비율 이상 유지하면 성공 — 끝까지 완벽할 필요는 없다 */
