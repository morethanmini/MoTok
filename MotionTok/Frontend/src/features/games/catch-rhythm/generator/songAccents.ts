/**
 * 곡의 첫 박이 얹히는 노트 슬롯 — {@code CatchRhythmStage}의 SONG_START_SLOT과 같아야 한다.
 * 곡을 슬롯 1에 걸어두므로 슬롯 i의 세기는 `SLOT_ACCENTS[i - 1]`이다.
 */
const SONG_START_SLOT = 1

/**
 * 이 슬롯이 곡의 **박(4분음표)** 위인가. 슬롯은 8분음표라 두 칸마다 한 박이다.
 *
 * <p>어느 쪽이 박인지는 이 표로 확인했다 — 홀수 슬롯의 평균 세기가 1.034, 짝수는 0.922로
 * 홀수가 박이다({@link SONG_START_SLOT}이 1이니 당연한 결과이고, 표가 그걸 뒷받침한다).</p>
 *
 * <p>공백을 메울 때 이 자리를 고른다. 아무 8분음표나 채우면 엇박에 노트가 떨어져서
 * "곡과 무관하게 하나 끼워넣은" 소리가 난다.</p>
 */
export function isOnBeat(slot: number): boolean {
  return (slot - SONG_START_SLOT) % 2 === 0
}

/**
 * 악센트가 밀도를 얼마나 흔들지.
 *
 * <p>1이면 표를 그대로 곱해 조용한 슬롯이 거의 비고, 0이면 예전처럼 균일하다. 0.75는
 * "곡을 따라간다"는 감각은 확실히 주면서, 소리가 옅은 구간에도 노트가 아주 없지는 않은 선이다 —
 * 1로 두면 인트로·브레이크에서 10초 넘게 노트가 끊겨 게임이 멈춘 것처럼 보인다.</p>
 */
const ACCENT_STRENGTH = 0.75
/**
 * 곱해지는 배율의 상한.
 *
 * <p>배율이 1/density를 넘으면 그 슬롯은 확률 1이 되어 잘려나가고, 잘린 만큼 전체 노트 수가
 * 목표보다 줄어든다. 2.0이면 HARD(density 0.48)에서 겨우 1에 닿는 정도라 손실이 거의 없다.</p>
 */
const ACCENT_MAX = 2

/**
 * 노트 슬롯의 밀도 배율. 표 밖(곡보다 긴 라운드, 곡이 시작하기 전 슬롯 0)은 1 —
 * 균일 배치로 돌아간다.
 *
 * <p>정적 상수만 보므로 시드가 같으면 방 전원이 같은 채보를 얻는다(결정성 유지).</p>
 */
export function slotAccent(slot: number): number {
  const raw = SLOT_ACCENTS[slot - SONG_START_SLOT]
  if (raw === undefined) return 1
  const weight = Math.min(ACCENT_MAX, raw / 100)
  return 1 + (weight - 1) * ACCENT_STRENGTH
}
